/**
 * Responsive Design System - Type Definitions
 * All coordinates are normalized to 0-1 ratios based on virtual canvas
 * Virtual canvas: 1000 x 500 (width x height)
 * Flutter renders at any screen size without transformation
 */

/**
 * Virtual Canvas Configuration
 * Use these constants to convert between pixels and ratios
 */
export const VIRTUAL_CANVAS = {
  WIDTH: 1000,
  HEIGHT: 500,
} as const;

/**
 * Style properties applicable to all elements
 * Uses normalized values (0-1 for colors, px for actual sizes when needed)
 */
export interface ResponsiveStyle {
  // Colors (hex format #RRGGBB or #RRGGBBAA)
  color?: string;                    // Text/stroke color
  backgroundColor?: string;           // Background color
  fillColor?: string;                 // Shape fill color
  strokeColor?: string;               // Border/stroke color
  
  // Sizing
  strokeWidth?: number;               // Absolute pixel width (not normalized)
  borderRadius?: number;              // Absolute pixel radius (not normalized)
  
  // Text styling (only for TEXT elements)
  fontSize?: number;                  // Relative font size in ratio (0-1)
  fontFamily?: string;                // Font family name (Arial, etc.)
  fontWeight?: number;                // 100-900
  fontStyle?: 'normal' | 'italic';
  
  // Text alignment
  textAlign?: 'left' | 'center' | 'right' | 'justify';
  lineHeight?: number;                // Relative line height (1.2, 1.5, etc.)
  letterSpacing?: number;             // Relative spacing in ratio
  
  // Effects
  textDecoration?: 'none' | 'underline' | 'overline' | 'line-through';
  shadow?: {
    offsetX: number;                  // Relative X offset (0-1)
    offsetY: number;                  // Relative Y offset (0-1)
    blur: number;                     // Relative blur radius (0-1)
    color: string;                    // Hex color
    opacity: number;                  // 0-1
  };
}

/**
 * Responsive Canvas Element
 * All position and size values are normalized (0-1)
 * These map directly to ratios of the virtual canvas
 */
export interface ResponsiveCanvasElement {
  // Identification
  id: string;                         // Unique element ID
  type: 'rectangle' | 'circle' | 'triangle' | 'text' | 'image'; // Element type
  
  // Position & Size (ALL NORMALIZED 0-1)
  x: number;                          // X position ratio (0 = left, 1 = right)
  y: number;                          // Y position ratio (0 = top, 1 = bottom)
  width: number;                      // Width ratio (0-1)
  height: number;                     // Height ratio (0-1)
  
  // Rotation & Layering
  rotation: number;                   // Degrees 0-360
  zIndex: number;                     // Layer order (integer)
  
  // Appearance
  opacity: number;                    // 0-1
  style: ResponsiveStyle;             // All styling properties
  
  // Content
  content?: string;                   // Text content or image URL
  
  // State
  visible: boolean;                   // Is element visible
  locked: boolean;                    // Is element locked for editing
  
  // Metadata
  createdAt: string;                  // ISO 8601 timestamp
  updatedAt: string;                  // ISO 8601 timestamp
}

/**
 * Responsive Design Metadata
 */
export interface ResponsiveDesignMetadata {
  title: string;                      // Design title (non-empty)
  description: string;                // Design description
  
  // Canvas dimensions (in virtual coordinates)
  virtualCanvasWidth: number;         // Always 1000
  virtualCanvasHeight: number;        // Always 500
  
  // Aspect ratio for Flutter rendering
  aspectRatio: number;                // width / height (always 2.0 for 1000x500)
  
  // Styling
  backgroundColor: string;            // Canvas background color (hex)
  
  // Metadata
  createdAt: string;                  // ISO 8601 timestamp
  updatedAt: string;                  // ISO 8601 timestamp
  createdBy: string;                  // Creator user ID/email
  tags: string[];                     // Search tags
  version: number;                    // Schema version (always 2)
}

/**
 * Responsive Design Document - Complete design ready for Firestore
 */
export interface ResponsiveDesignDocument {
  // Document ID (auto-generated by Firestore)
  id: string;
  
  // Ownership & Access
  userId: string;                     // Owner's UID
  userEmail: string;                  // Owner's email
  isPublic: boolean;                  // Visibility flag
  
  // Design Content
  metadata: ResponsiveDesignMetadata;
  elements: ResponsiveCanvasElement[]; // Array of elements (all normalized)
  
  // Firestore metadata
  createdAt: any;                     // Firestore Timestamp
  updatedAt: any;                     // Firestore Timestamp
  
  // Stats
  viewCount: number;
  likes: number;
  likedBy?: string[];                 // Array of user IDs who liked
  collaborators?: string[];           // Array of collaborator UIDs
}

/**
 * Helper types for conversion
 */
export interface PixelCoordinates {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface NormalizedCoordinates {
  x: number;                          // 0-1
  y: number;                          // 0-1
  width: number;                      // 0-1
  height: number;                     // 0-1
}

/**
 * Save response
 */
export interface SaveDesignResponse {
  success: boolean;
  designId?: string;
  error?: string;
  timestamp?: string;
}

/**
 * Design update options
 */
export interface UpdateDesignOptions {
  isPublic?: boolean;
  tags?: string[];
  description?: string;
}
