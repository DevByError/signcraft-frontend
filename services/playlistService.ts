/**
 * Playlist Service
 * Manages playlists that reference multiple designs with durations
 * Playlists are stored in the 'playlists' collection
 * They reference design IDs only - NO data duplication
 */

// API base URL for backend integration
const API_BASE = import.meta.env.VITE_API_URL || 'http://localhost:5000';

import authService from './authService';

// Local storage removed - use backend API only

// ==================== TypeScript Interfaces ====================

/**
 * Design reference within a playlist
 * Contains only the design ID and playback duration
 */
export interface PlaylistDesignReference {
  designId: string;      // Reference to design in 'designs' collection
  duration: number;      // Duration in seconds for this design
  order: number;         // Display order in playlist
}

/**
 * Complete playlist document structure
 */
export interface PlaylistDocument {
  id: string;                              // Auto-generated by Firestore
  userId: string;                          // Owner's UID
  userEmail: string;                       // Owner's email
  name: string;                            // Playlist name
  description: string;                     // Optional description
  designReferences: PlaylistDesignReference[]; // Array of design references
  totalDuration: number;                   // Total duration in seconds (calculated)
  isPublic: boolean;                       // Visibility flag
  createdAt: string;                       // ISO timestamp
  updatedAt: string;                       // ISO timestamp
}

/**
 * Playlist with populated design data (for display)
 */
export interface PlaylistWithDesigns {
  id: string;
  userId: string;
  userEmail: string;
  name: string;
  description: string;
  designs: Array<{
    designId: string;
    duration: number;
    order: number;
    title: string;           // Populated from design
    thumbnail: string;       // Populated from design
    canvasSize: string;      // Populated from design
  }>;
  totalDuration: number;
  itemCount: number;
  isPublic: boolean;
  createdAt: string;
  updatedAt: string;
}

// No collections; using a single local array under STORAGE_KEY

// ==================== Helper Functions ====================

const getCurrentUser = () => {
  const u = authService.getUser();
  if (u && u.id) return { uid: u.id, email: u.email || '' };
  return { uid: 'guest-user-123', email: 'guest@signcraft.com' };
};

const calculateTotalDuration = (references: PlaylistDesignReference[]): number => {
  return references.reduce((total, ref) => total + ref.duration, 0);
};

// ==================== Core CRUD Operations ====================

/**
 * Create a new playlist
 */
export const createPlaylist = async (
  name: string,
  description: string = '',
  designReferences: PlaylistDesignReference[] = [],
  isPublic: boolean = false
): Promise<{ success: boolean; playlistId?: string; error?: string }> => {
  try {
    const currentUser = getCurrentUser();
    const now = new Date().toISOString();

    const playlistData: Omit<PlaylistDocument, 'id'> = {
      userId: currentUser.uid,
      userEmail: currentUser.email,
      name: name.trim(),
      description: description.trim(),
      designReferences: designReferences.sort((a, b) => a.order - b.order),
      totalDuration: calculateTotalDuration(designReferences),
      isPublic,
      createdAt: now,
      updatedAt: now,
    };

    const playlists = readAll();
    const id = Math.random().toString(36).slice(2, 10);
    const record = { id, ...playlistData } as any;
    playlists.push(record);
    writeAll(playlists);

    console.log('✅ [PLAYLIST] Created playlist:', {
      id,
      name,
      designs: designReferences.length,
      duration: playlistData.totalDuration,
    });

    return {
      success: true,
      playlistId: id,
    };
  } catch (error: any) {
    console.error('❌ [PLAYLIST] Error creating playlist:', error);
    return {
      success: false,
      error: error.message || 'Failed to create playlist',
    };
  }
};

/**
 * Update an existing playlist
 */
export const updatePlaylist = async (
  playlistId: string,
  updates: {
    name?: string;
    description?: string;
    designReferences?: PlaylistDesignReference[];
    isPublic?: boolean;
  }
): Promise<{ success: boolean; error?: string }> => {
  try {
    const playlists = readAll();
    const idx = playlists.findIndex((p: any) => p.id === playlistId);
    if (idx < 0) {
      return { success: false, error: 'Playlist not found' };
    }
    const updateData: any = { ...playlists[idx], updatedAt: new Date().toISOString() };

    if (updates.name !== undefined) {
      updateData.name = updates.name.trim();
    }
    
    if (updates.description !== undefined) {
      updateData.description = updates.description.trim();
    }
    
    if (updates.designReferences !== undefined) {
      updateData.designReferences = updates.designReferences.sort((a, b) => a.order - b.order);
      updateData.totalDuration = calculateTotalDuration(updates.designReferences);
    }
    
    if (updates.isPublic !== undefined) {
      updateData.isPublic = updates.isPublic;
    }

    playlists[idx] = updateData;
    writeAll(playlists);

    console.log('✅ [PLAYLIST] Updated playlist:', playlistId);

    return { success: true };
  } catch (error: any) {
    console.error('❌ [PLAYLIST] Error updating playlist:', error);
    return {
      success: false,
      error: error.message || 'Failed to update playlist',
    };
  }
};

/**
 * Delete a playlist
 */
export const deletePlaylist = async (
  playlistId: string
): Promise<{ success: boolean; error?: string }> => {
  try {
    const playlists = readAll();
    const next = playlists.filter((p: any) => p.id !== playlistId);
    writeAll(next);

    console.log('✅ [PLAYLIST] Deleted playlist:', playlistId);

    return { success: true };
  } catch (error: any) {
    console.error('❌ [PLAYLIST] Error deleting playlist:', error);
    return {
      success: false,
      error: error.message || 'Failed to delete playlist',
    };
  }
};

/**
 * Get a single playlist by ID
 */
export const getPlaylistById = async (
  playlistId: string
): Promise<PlaylistDocument | null> => {
  try {
    const playlists = readAll();
    const found = playlists.find((p: any) => p.id === playlistId);
    return found || null;
  } catch (error: any) {
    console.error(`❌ [PLAYLIST] Error fetching playlist ${playlistId}:`, error.message || error);
    return null;
  }
};

/**
 * Get all playlists for the current user
 */
export const getUserPlaylists = async (
  limitCount: number = 50
): Promise<PlaylistDocument[]> => {
  try {
    const currentUser = getCurrentUser();
    const all = readAll();
    const mine = all.filter((p: any) => p.userId === currentUser.uid);
    mine.sort((a: any, b: any) => Date.parse(b.updatedAt || '') - Date.parse(a.updatedAt || ''));
    return mine.slice(0, limitCount);
  } catch (error: any) {
    console.error('❌ [PLAYLIST] Error fetching user playlists:', error);
    throw error;
  }
};

/**
 * Get all public playlists
 */
export const getPublicPlaylists = async (
  limitCount: number = 50
): Promise<PlaylistDocument[]> => {
  try {
    const all = readAll();
    const pubs = all.filter((p: any) => p.isPublic);
    pubs.sort((a: any, b: any) => Date.parse(b.updatedAt || '') - Date.parse(a.updatedAt || ''));
    return pubs.slice(0, limitCount);
  } catch (error: any) {
    console.error('❌ [PLAYLIST] Error fetching public playlists:', error);
    throw error;
  }
};

/**
 * Duplicate a playlist
 */
export const duplicatePlaylist = async (
  playlistId: string
): Promise<{ success: boolean; playlistId?: string; error?: string }> => {
  try {
    const originalPlaylist = await getPlaylistById(playlistId);
    
    if (!originalPlaylist) {
      return {
        success: false,
        error: 'Playlist not found',
      };
    }

    return await createPlaylist(
      `${originalPlaylist.name} (Copy)`,
      originalPlaylist.description,
      originalPlaylist.designReferences,
      originalPlaylist.isPublic
    );
  } catch (error: any) {
    console.error('❌ [PLAYLIST] Error duplicating playlist:', error);
    return {
      success: false,
      error: error.message || 'Failed to duplicate playlist',
    };
  }
};

// ==================== Helper Functions for UI ====================

/**
 * Add a design to a playlist
 */
export const addDesignToPlaylist = async (
  playlistId: string,
  designId: string,
  duration: number = 10
): Promise<{ success: boolean; error?: string }> => {
  try {
    const playlist = await getPlaylistById(playlistId);
    
    if (!playlist) {
      return { success: false, error: 'Playlist not found' };
    }

    const newReference: PlaylistDesignReference = {
      designId,
      duration,
      order: playlist.designReferences.length,
    };

    const updatedReferences = [...playlist.designReferences, newReference];

    return await updatePlaylist(playlistId, {
      designReferences: updatedReferences,
    });
  } catch (error: any) {
    console.error('❌ [PLAYLIST] Error adding design to playlist:', error);
    return {
      success: false,
      error: error.message || 'Failed to add design',
    };
  }
};

/**
 * Remove a design from a playlist
 */
export const removeDesignFromPlaylist = async (
  playlistId: string,
  designId: string
): Promise<{ success: boolean; error?: string }> => {
  try {
    const playlist = await getPlaylistById(playlistId);
    
    if (!playlist) {
      return { success: false, error: 'Playlist not found' };
    }

    const updatedReferences = playlist.designReferences
      .filter(ref => ref.designId !== designId)
      .map((ref, index) => ({ ...ref, order: index }));

    return await updatePlaylist(playlistId, {
      designReferences: updatedReferences,
    });
  } catch (error: any) {
    console.error('❌ [PLAYLIST] Error removing design from playlist:', error);
    return {
      success: false,
      error: error.message || 'Failed to remove design',
    };
  }
};

/**
 * Reorder designs in a playlist
 */
export const reorderPlaylistDesigns = async (
  playlistId: string,
  designReferences: PlaylistDesignReference[]
): Promise<{ success: boolean; error?: string }> => {
  try {
    // Ensure proper order values
    const reordered = designReferences.map((ref, index) => ({
      ...ref,
      order: index,
    }));

    return await updatePlaylist(playlistId, {
      designReferences: reordered,
    });
  } catch (error: any) {
    console.error('❌ [PLAYLIST] Error reordering designs:', error);
    return {
      success: false,
      error: error.message || 'Failed to reorder designs',
    };
  }
};

