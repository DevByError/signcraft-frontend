/**
 * Screen Service
 * Manages display screens that show playlists
 * Screens are stored in the 'screens' collection
 */

import {
  collection,
  addDoc,
  updateDoc,
  deleteDoc,
  getDoc,
  getDocs,
  doc,
  query,
  where,
  Timestamp,
} from 'firebase/firestore';
import { db, auth } from './firebaseService';

// ==================== TypeScript Interfaces ====================

/**
 * Complete screen document structure
 */
export interface ScreenDocument {
  id: string;                    // Auto-generated by Firestore
  screenId: string;              // Custom ID (scr01, scr02, etc.)
  userId: string;                // Owner's UID
  userEmail: string;             // Owner's email
  name: string;                  // Screen name
  location: string;              // Physical location
  resolution: string;            // Display resolution (e.g., "1920x1080")
  status: 'online' | 'offline';  // Connection status
  lastSeen: Timestamp;           // Last connection timestamp
  ipAddress: string;             // IP address
  playlistId?: string;           // Currently assigned playlist ID
  playlistName?: string;         // Currently assigned playlist name (for display)
  createdAt: Timestamp;          // Creation timestamp
  updatedAt: Timestamp;          // Last update timestamp
}

const SCREENS_COLLECTION = 'screens';

// ==================== Helper Functions ====================

const getCurrentUser = () => {
  const currentUser = auth.currentUser;
  return {
    uid: currentUser?.uid || 'guest-user-123',
    email: currentUser?.email || 'guest@signcraft.com',
  };
};

/**
 * Generate next screen ID (scr01, scr02, etc.)
 */
const generateNextScreenId = async (userId: string): Promise<string> => {
  try {
    const q = query(
      collection(db, SCREENS_COLLECTION),
      where('userId', '==', userId)
    );
    const snapshot = await getDocs(q);
    
    // Find the highest number
    let maxNum = 0;
    snapshot.docs.forEach(doc => {
      const screenId = doc.data().screenId as string;
      if (screenId && screenId.startsWith('scr')) {
        const num = parseInt(screenId.substring(3), 10);
        if (!isNaN(num) && num > maxNum) {
          maxNum = num;
        }
      }
    });
    
    // Generate next ID
    const nextNum = maxNum + 1;
    return `scr${String(nextNum).padStart(2, '0')}`;
  } catch (error) {
    console.error('Error generating screen ID:', error);
    return 'scr01'; // Fallback
  }
};

// ==================== Core CRUD Operations ====================

/**
 * Create a new screen
 */
export const createScreen = async (
  name: string,
  location: string,
  resolution: string = '1920x1080',
  ipAddress: string = '',
  playlistId?: string,
  playlistName?: string
): Promise<{ success: boolean; screenId?: string; error?: string }> => {
  try {
    const user = getCurrentUser();
    const customScreenId = await generateNextScreenId(user.uid);
    
    const screenData = {
      screenId: customScreenId,
      userId: user.uid,
      userEmail: user.email,
      name,
      location,
      resolution,
      status: 'offline' as const,
      lastSeen: Timestamp.now(),
      ipAddress,
      playlistId: playlistId || null,
      playlistName: playlistName || null,
      createdAt: Timestamp.now(),
      updatedAt: Timestamp.now(),
    };

    const docRef = await addDoc(collection(db, SCREENS_COLLECTION), screenData);
    
    console.log('✅ [SCREEN] Created successfully:', docRef.id, `(${customScreenId})`);
    return { success: true, screenId: docRef.id };
  } catch (error) {
    console.error('❌ [SCREEN] Error creating screen:', error);
    return {
      success: false,
      error: error instanceof Error ? error.message : 'Unknown error',
    };
  }
};

/**
 * Get all screens for current user
 */
export const getUserScreens = async (limit: number = 100): Promise<ScreenDocument[]> => {
  try {
    const user = getCurrentUser();
    const q = query(
      collection(db, SCREENS_COLLECTION),
      where('userId', '==', user.uid)
    );

    const snapshot = await getDocs(q);
    const screens = snapshot.docs.map(doc => ({
      id: doc.id,
      ...doc.data(),
    })) as ScreenDocument[];

    // Sort by screenId in memory
    screens.sort((a, b) => a.screenId.localeCompare(b.screenId));

    return screens.slice(0, limit);
  } catch (error) {
    console.error('❌ [SCREEN] Error fetching screens:', error);
    throw error;
  }
};

/**
 * Get a single screen by ID
 */
export const getScreen = async (screenId: string): Promise<ScreenDocument | null> => {
  try {
    const docRef = doc(db, SCREENS_COLLECTION, screenId);
    const docSnap = await getDoc(docRef);

    if (!docSnap.exists()) {
      return null;
    }

    return {
      id: docSnap.id,
      ...docSnap.data(),
    } as ScreenDocument;
  } catch (error) {
    console.error('❌ [SCREEN] Error fetching screen:', error);
    return null;
  }
};

