/**
 * Adds a collaborator to a design
 * @param designId - Design document ID
 * @param collaboratorUid - UID of user to add
 */
export const addCollaborator = async (
  designId: string,
  collaboratorUid: string
): Promise<SaveDesignResponse> => {
  try {
    const currentUser = getCurrentUser();

    const designRef = doc(db, DESIGNS_COLLECTION, designId);
    const docSnap = await getDoc(designRef);
    
    if (!docSnap.exists()) {
      return {
        success: false,
        error: 'Design not found.',
      };
    }

    const docData = docSnap.data() as any;
    if (docData.userId !== currentUser.uid) {
      return {
        success: false,
        error: 'Only the owner can add collaborators.',
      };
    }

    const collaborators = docData.collaborators ?? [];
    if (!collaborators.includes(collaboratorUid)) {
      collaborators.push(collaboratorUid);
      await updateDoc(designRef, {
        collaborators,
        updatedAt: Timestamp.now(),
      });
    }

    return {
      success: true,
      designId,
      timestamp: new Date().toISOString(),
    };
  } catch (error: any) {
    console.error('Error adding collaborator:', error);
    return {
      success: false,
      error: error.message || 'Failed to add collaborator.',
    };
  }
};
