/**
 * Complete Firestore design document structure
 * Flutter clients will receive this exact structure
 */
export interface FirestoreDesignDocument {
  // Document ID (auto-generated by Firestore)
  id: string;
  
  // Ownership & Access Control
  userId: string; // Required: Document owner's UID
  userEmail: string; // Required: Document owner's email
  isPublic: boolean; // Required: Visibility flag
  
  // Design Content (exact structure)
  metadata: {
    title: string; // Non-empty
    description: string; // May be empty
    canvasWidth: number; // Pixels, positive
    canvasHeight: number; // Pixels, positive
    canvasColor: string; // Hex format #RRGGBB
    createdAt: string; // ISO 8601
    updatedAt: string; // ISO 8601
    createdBy: string; // User ID/email
    tags: string[]; // Array of tags
    version: number; // Schema version
  };
  
  // Design Elements (array of strict element objects)
  designJSON: {
    elements: Array<{
      id: string;
      type: string;
      content: string;
      x: number;
      y: number;
      width: number;
      height: number;
      radius?: number;
      opacity: number;
      rotation: number;
      zIndex: number;
      color?: string;
      backgroundColor?: string;
      fillColor?: string;
      strokeColor?: string;
      strokeWidth?: number;
      borderRadius?: number;
      fontSize?: number;
      textStyle?: {
        bold: boolean;
        italic: boolean;
        underline: boolean;
        textAlign: 'left' | 'center' | 'right' | 'justify';
        fontFamily: string;
        letterSpacing: number;
        lineHeight: number;
      };
      shadow?: {
        offsetX: number;
        offsetY: number;
        blur: number;
        color: string;
        opacity: number;
      };
      visible: boolean;
      locked: boolean;
    }>;
    totalElements: number;
    version: string;
  };
  
  // Metadata for Firestore
  createdAt: Timestamp;
  updatedAt: Timestamp;
  
  // Analytics & Engagement
  viewCount: number; // Default: 0
  likes: number; // Default: 0
  
  // Collaboration
  collaborators: string[]; // Array of user UIDs
}

const DESIGNS_COLLECTION = 'designs';
const MAX_RETRIES = 3;
const RETRY_DELAY = 1000; // ms
const DEFAULT_USER_ID = 'local_user'; // Default user ID for non-authenticated sessions
const DEFAULT_USER_EMAIL = 'local@signcraft.dev'; // Default email for non-authenticated sessions

/**
 * Get current user info (always uses guest user - no authentication)
 */
const getCurrentUser = () => {
  // Always use guest user (no authentication)
  return {
    uid: DEFAULT_USER_ID,
    email: DEFAULT_USER_EMAIL,
    isAuthenticated: false,
  };
};

/**
 * Retry logic for failed Firestore operations
 */
const retryOperation = async <T>(
  operation: () => Promise<T>,
  retries = MAX_RETRIES
): Promise<T> => {
  try {
    return await operation();
  } catch (error: any) {
    if (retries > 0 && (error.code === 'unavailable' || error.code === 'deadline-exceeded')) {
      await new Promise(resolve => setTimeout(resolve, RETRY_DELAY));
      return retryOperation(operation, retries - 1);
    }
    throw error;
  }
};

/**
 * Converts Firestore document snapshot to client-side design document
 */
const mapFirestoreDocToDesign = (docSnap: QueryDocumentSnapshot<DocumentData>): FirestoreDesignDocument => {
  const data = docSnap.data();
  return {
    id: docSnap.id,
    ...data,
  } as FirestoreDesignDocument;
};

/**
 * Saves a design to Firestore with strict validation
 * @param design - The exported design object with exact structure
 * @param options - Additional save options
 * @returns Save response with design ID and timestamp
 */
export const saveDesignToFirestore = async (
  design: ExportedDesignData,
  options: SaveDesignOptions = {}
): Promise<SaveDesignResponse> => {
  try {
    // DEBUG: Log before validation
    console.log('🚀 [FIRESTORE SAVE] Attempting to save design:', {
      title: design.metadata.title,
      totalElements: design.designJSON.elements.length,
      textElements: design.designJSON.elements.filter((el: any) => el.type === 'TEXT').length,
      elements: design.designJSON.elements.map((el: any) => ({
        id: el.id,
        type: el.type,
        content: el.content,
        contentLength: el.content ? el.content.length : 0,
      }))
    });

    // Comprehensive validation
    const validation = validateExportedDesign(design);
    if (!validation.isValid) {
      console.error('❌ [FIRESTORE SAVE] Design validation failed:', validation.errors);
      return {
        success: false,
        error: `Invalid design structure: ${validation.errors.join(', ')}`,
      };
    }

    // Validate each element
    for (let i = 0; i < design.designJSON.elements.length; i++) {
      const elementValidation = validateCanvasElement(design.designJSON.elements[i]);
      if (!elementValidation.isValid) {
        console.error(`❌ [FIRESTORE SAVE] Element ${i} validation failed:`, elementValidation.errors);
        return {
          success: false,
          error: `Element ${i} validation failed: ${elementValidation.errors.join(', ')}`,
        };
      }
    }

    const currentUser = getCurrentUser();
    const now = Timestamp.now();

    // Prepare Firestore document with exact structure
    const documentData: Omit<FirestoreDesignDocument, 'id'> = {
      userId: currentUser.uid,
      userEmail: currentUser.email,
      isPublic: Boolean(options.isPublic ?? false),
      
      metadata: {
        title: design.metadata.title,
        description: design.metadata.description,
        canvasWidth: design.metadata.canvasWidth,
        canvasHeight: design.metadata.canvasHeight,
        canvasColor: design.metadata.canvasColor,
        createdAt: design.metadata.createdAt,
        updatedAt: design.metadata.updatedAt,
        createdBy: currentUser.uid,
        tags: Array.isArray(options.tags) ? options.tags : design.metadata.tags,
        version: 1,
      },
      
      designJSON: design.designJSON,
      
      createdAt: now,
      updatedAt: now,
      
      viewCount: 0,
      likes: 0,
      
      collaborators: [],
    };

    // Save with retry logic
    const designId = await retryOperation(async () => {
      const docRef = await addDoc(
        collection(db, DESIGNS_COLLECTION),
        documentData
      );
      return docRef.id;
    });

    // DEBUG: Log successful save
    console.log('✅ [FIRESTORE SAVE] Design saved successfully:', {
      designId,
      title: design.metadata.title,
      elements: design.designJSON.elements.length,
      textElements: design.designJSON.elements.filter((el: any) => el.type === 'TEXT').length,
      timestamp: new Date().toISOString(),
    });

    return {
      success: true,
      designId,
      timestamp: new Date().toISOString(),
    };
  } catch (error: any) {
    console.error('❌ Error saving design to Firestore:', error);
    return {
      success: false,
      error: error.message || 'Failed to save design. Please try again.',
    };
  }
};

/**
 * Updates an existing design in Firestore with validation
 * @param designId - The design document ID
 * @param design - Updated design data
 * @returns Update response with timestamp
 */
/**
 * Helper function to recursively remove undefined values from objects
 */
const stripUndefinedValues = (obj: any): any => {
  if (obj === null || typeof obj !== 'object') {
    return obj;
  }
  
  if (Array.isArray(obj)) {
    return obj.map(item => stripUndefinedValues(item)).filter(item => item !== undefined);
  }
  
  const cleaned: any = {};
  for (const key in obj) {
    const value = obj[key];
    if (value !== undefined) {
      cleaned[key] = stripUndefinedValues(value);
    }
  }
  return cleaned;
};

export const updateDesignInFirestore = async (
  designId: string,
  design: ExportedDesignData
): Promise<SaveDesignResponse> => {
  try {
    // Validate design
    const validation = validateExportedDesign(design);
    if (!validation.isValid) {
      return {
        success: false,
        error: `Invalid design structure: ${validation.errors.join(', ')}`,
      };
    }

    const currentUser = getCurrentUser();

    const designRef = doc(db, DESIGNS_COLLECTION, designId);
    const docSnap = await getDoc(designRef);
    
    if (!docSnap.exists()) {
      return {
        success: false,
        error: 'Design not found.',
      };
    }

    // Allow editing own designs (check userId matches)
    const docData = docSnap.data() as any;
    if (docData.userId !== currentUser.uid) {
      return {
        success: false,
        error: 'You can only edit your own designs.',
      };
    }

    const now = Timestamp.now();

    // Complete data replacement - delete old data and set new data
    const updateData: FirestoreDesignDocument = {
      id: designId,
      userId: currentUser.uid,
      userEmail: currentUser.email || '',
      isPublic: docData.isPublic ?? false,
      metadata: {
        title: design.metadata.title,
        description: design.metadata.description,
        canvasWidth: design.metadata.canvasWidth,
        canvasHeight: design.metadata.canvasHeight,
        canvasColor: design.metadata.canvasColor,
        createdAt: design.metadata.createdAt,
        updatedAt: new Date().toISOString(),
        createdBy: currentUser.uid,
        tags: design.metadata.tags,
        version: (docData.metadata?.version ?? 0) + 1,
      },
      designJSON: design.designJSON,
      createdAt: docData.createdAt,
      updatedAt: now,
      viewCount: docData.viewCount ?? 0,
      likes: docData.likes ?? 0,
      collaborators: docData.collaborators ?? [],
    };

    // Remove any undefined values before saving to Firebase
    const cleanedData = stripUndefinedValues(updateData);

    await retryOperation(async () => {
      // Complete document replacement to ensure old data is completely deleted
      await setDoc(designRef, cleanedData, { merge: false });
    });

    return {
      success: true,
      designId,
      timestamp: new Date().toISOString(),
    };
  } catch (error: any) {
    console.error('Error updating design:', error);
    return {
      success: false,
      error: error.message || 'Failed to update design.',
    };
  }
};

/**
 * Retrieves a single design by ID with exact Firestore structure
 * @param designId - The design document ID
 * @returns Design document or null
 */
export const getDesignById = async (designId: string): Promise<FirestoreDesignDocument | null> => {
  try {
    const docSnap = await getDoc(doc(db, DESIGNS_COLLECTION, designId));
    if (docSnap.exists()) {
      return mapFirestoreDocToDesign(docSnap as QueryDocumentSnapshot<DocumentData>);
    }
    return null;
  } catch (error: any) {
    console.error('Error retrieving design:', error);
    return null;
  }
};

/**
 * Retrieves all designs without authentication (for development/demo)
 * @param maxResults - Maximum number of results (default 50)
 * @returns Array of all designs with exact structure
 */
export const getAllDesigns = async (maxResults: number = 50): Promise<FirestoreDesignDocument[]> => {
  try {
    const q = query(
      collection(db, DESIGNS_COLLECTION),
      orderBy('updatedAt', 'desc'),
      limit(maxResults)
    );

    const querySnapshot = await getDocs(q);
    return querySnapshot.docs.map(doc => 
      mapFirestoreDocToDesign(doc as QueryDocumentSnapshot<DocumentData>)
    );
  } catch (error: any) {
    console.error('Error retrieving all designs:', error);
    return [];
  }
};

/**
 * Retrieves all designs for the current authenticated user
 * @param maxResults - Maximum number of results (default 50)
 * @returns Array of user's designs with exact structure
 */
export const getUserDesigns = async (maxResults: number = 50): Promise<FirestoreDesignDocument[]> => {
  try {
    const currentUser = getCurrentUser();

    const q = query(
      collection(db, DESIGNS_COLLECTION),
      where('userId', '==', currentUser.uid)
      // Note: orderBy removed to avoid composite index requirement
      // We'll sort in memory instead
    );

    const querySnapshot = await getDocs(q);
    const designs = querySnapshot.docs.map(doc => 
      mapFirestoreDocToDesign(doc as QueryDocumentSnapshot<DocumentData>)
    );

    // Sort by updatedAt in memory (newest first)
    designs.sort((a, b) => {
      const timeA = a.metadata.updatedAt ? new Date(a.metadata.updatedAt).getTime() : 0;
      const timeB = b.metadata.updatedAt ? new Date(b.metadata.updatedAt).getTime() : 0;
      return timeB - timeA;
    });

    // Apply limit after sorting
    return designs.slice(0, maxResults);
  } catch (error: any) {
    console.error('Error retrieving user designs:', error);
    return [];
  }
};

/**
 * Retrieves public designs with optional filtering
 * @param filters - Query filters (tags, creator, etc.)
 * @param maxResults - Maximum number of results
 * @returns Array of public designs with exact structure
 */
export const getPublicDesigns = async (
  filters?: {
    tags?: string[];
    createdBy?: string;
    search?: string;
  },
  maxResults: number = 20
): Promise<FirestoreDesignDocument[]> => {
  try {
    const constraints: QueryConstraint[] = [
      where('isPublic', '==', true),
      orderBy('updatedAt', 'desc'),
      limit(maxResults),
    ];

    if (filters?.createdBy) {
      constraints.push(where('userId', '==', filters.createdBy));
    }

    const q = query(collection(db, DESIGNS_COLLECTION), ...constraints);
    const querySnapshot = await getDocs(q);
    
    let results = querySnapshot.docs.map(doc =>
      mapFirestoreDocToDesign(doc as QueryDocumentSnapshot<DocumentData>)
    );

    // Client-side filtering for tags and search (Firestore array-contains has limitations)
    if (filters?.tags && filters.tags.length > 0) {
      results = results.filter(design =>
        filters.tags!.some(tag => design.metadata.tags?.includes(tag))
      );
    }

    if (filters?.search) {
      const searchLower = filters.search.toLowerCase();
      results = results.filter(design =>
        design.metadata.title.toLowerCase().includes(searchLower) ||
        design.metadata.description?.toLowerCase().includes(searchLower)
      );
    }

    return results;
  } catch (error: any) {
    console.error('Error retrieving public designs:', error);
    return [];
  }
};

/**
 * Deletes a design from Firestore (owner only)
 * @param designId - The design document ID
 * @returns Deletion response
 */
export const deleteDesignFromFirestore = async (
  designId: string
): Promise<SaveDesignResponse> => {
  try {
    const currentUser = getCurrentUser();

    const designRef = doc(db, DESIGNS_COLLECTION, designId);
    const docSnap = await getDoc(designRef);
    
    if (!docSnap.exists()) {
      return {
        success: false,
        error: 'Design not found.',
      };
    }

    const docData = docSnap.data() as any;
    if (docData.userId !== currentUser.uid) {
      return {
        success: false,
        error: 'You can only delete your own designs.',
      };
    }

    await retryOperation(async () => {
      await deleteDoc(designRef);
    });

    return {
      success: true,
      timestamp: new Date().toISOString(),
    };
  } catch (error: any) {
    console.error('Error deleting design:', error);
    return {
      success: false,
      error: error.message || 'Failed to delete design.',
    };
  }
};

/**
 * Increments view count (idempotent for Flutter clients)
 * @param designId - The design document ID
 */
export const incrementDesignViewCount = async (designId: string): Promise<boolean> => {
  try {
    const designRef = doc(db, DESIGNS_COLLECTION, designId);
    const docSnap = await getDoc(designRef);
    
    if (docSnap.exists()) {
      const currentViewCount = docSnap.data().viewCount ?? 0;
      await updateDoc(designRef, {
        viewCount: currentViewCount + 1,
        updatedAt: Timestamp.now(),
      });
      return true;
    }
    return false;
  } catch (error: any) {
    console.error('Error incrementing view count:', error);
    return false;
  }
};

